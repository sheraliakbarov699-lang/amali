# reverse() - listni teskarisiga o'giradi
fruits = ["apple", "banana", "cherry"]
fruits.reverse()
print("Teskari list:", fruits)

# sort() - matnlarni alfavit bo'yicha tartiblaydi
cars = ["Ford", "BMW", "Volvo"]
cars.sort()
print("Alfavit bo'yicha:", cars)

# sort() - harflarni tartiblaydi
letters = ["d", "f", "e", "a", "c", "b"]
letters.sort()
print("Harflar tartibi:", letters)

# sort() - sonlarni o'sish tartibida joylaydi
numbers = [5, 2, 8, 1, 4]
numbers.sort()
print("Sonlar tartibi:", numbers)